import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { chromium, expect as baseExpect } from "@playwright/test";
import { Store } from "../server/store.js";
import { Service } from "../server/service.js";
import { bootstrap } from "../server/bootstrap.js";
import { createApp } from "../server/index.js";
import { philippineDate, addDays } from "../server/rules.js";
import { utilityPdf, utilityEmail } from "./fixtures.js";
const expect=baseExpect.configure({timeout:30000});

test("phone utility journey: PDF upload, correction, shared bills, calendar, alerts, personal marks, email duplicate and real image OCR", {timeout:120000}, async () => {
  const dir=mkdtempSync(join(tmpdir(),"propertypro-utility-journey-"));
  const store=new Store(join(dir,"test.sqlite")), service=new Service(store), password="UtilityJourney!2026";
  bootstrap(service,{adminPassword:password,managerPassword:password,tenantPassword:password,demo:true,demoStart:"2026-01-31"});
  const origin="http://127.0.0.1:8110", app=createApp({store,dataDir:dir,env:{ALLOWED_ORIGINS:origin}});
  const now=philippineDate(), due=addDays(now,4), start=now.slice(0,7)+"-01";
  const text=`SYNTHETIC TEST BILL - NOT A PROVIDER DOCUMENT\nMeralco\nAccount: UNMAPPED-TEST\nAmount Due: 100.01\nDue Date: ${due}\nBilling Period: ${start} to ${now}`;
  const pdf=utilityPdf(text), errors=[];
  let browser;
  await new Promise(r=>app.server.listen(8110,"127.0.0.1",r));
  try {
    browser=await chromium.launch({headless:true,...(process.platform==="win32"?{executablePath:process.env.BROWSER_EXECUTABLE||"C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe"}:{})});
    const manager=await browser.newPage({viewport:{width:390,height:844}});
    manager.on("pageerror",e=>errors.push(e.message));
    const login=async(page,email)=>{
      await page.goto(origin+"/#/login");
      await page.locator("#login-email").fill(email);
      await page.locator("#login-password").fill(password);
      await page.locator("[data-sign-in]").click();
      await expect(page.locator(".app-shell")).toBeVisible();
    };
    await login(manager,"manager@propertypro.ph");
    await manager.goto(origin+"/#/bills?tab=incoming");
    await manager.getByRole("button",{name:"Upload source",exact:true}).click();
    await manager.locator('.modal input[type="file"]').setInputFiles({name:"sample.pdf",mimeType:"application/pdf",buffer:pdf});
    await manager.locator("[data-upload]").click();
    await expect(manager.locator(".modal")).toHaveCount(0);
    await expect.poll(()=>store.all("incoming").length).toBe(1);
    const source=store.all("incoming")[0];
    assert.equal(source.processingOutcome,"exception");
    assert.equal(store.all("bills").filter(b=>b.sourceId===source.id).length,0);
    await manager.goto(origin+"/#/bills?tab=exceptions");
    await manager.locator(`[data-case-select="${source.id}"]`).click();
    await manager.getByRole("button",{name:"Correct directly instead"}).click();
    await expect(manager.locator(".source-review__pdf")).toHaveAttribute("src",/^blob:/);
    await expect(manager.locator(".case-fields")).toContainText("100.01");
    await manager.locator('.case-edit select[name="field"]').selectOption("accountRef");
    await manager.locator('input[name="value"]').fill("MER-552194");
    await manager.locator('textarea[name="reason"]').fill("Synthetic fixture: verified account belongs to configured unit B-203.");
    await manager.locator("[data-case-save]").click();
    await expect(manager.locator(".case-sheet__status")).toContainText("Processed");
    const bills=store.all("bills").filter(b=>b.sourceId===source.id);
    const dto=service.bills(store.get("users","usr-manager"),{}).find(b=>b.sourceId===source.id);
    assert.equal(dto.utilityProvider,store.get("incoming",source.id).provider);
    assert.match(dto.utilityProvider,/meralco/i);
    assert.equal(store.get("bills",dto.id).utilityProvider,undefined,"provider is read from the protected source, not duplicated in storage");
    assert.equal(bills.length,3);
    assert.equal(bills.reduce((sum,b)=>sum+Math.round(b.totalDue*100),0),10001);
    assert.equal(store.get("incoming",source.id).ocrStatus,"validated");
    assert.ok(store.all("corrections").some(c=>c.sourceId===source.id));
    const rentBefore=store.all("bills").filter(b=>b.lines.every(l=>l.category==="rent")).map(b=>[b.id,b.paymentStatus]);
    const bill=bills.find(b=>b.tenantId==="tnt-001"), other=bills.find(b=>b.tenantId!=="tnt-001");
    const tenant=await browser.newPage({viewport:{width:390,height:844}});
    tenant.on("pageerror",e=>errors.push(e.message));
    await login(tenant,"maria.santos@gmail.com");
    const mark=tenant.locator(`[data-home-track-utility="${bill.id}"]`);
    await expect(mark).toHaveText("Mark personally paid");
    const monthDifference=Number(due.slice(0,4))*12+Number(due.slice(5,7))-Number(now.slice(0,4))*12-Number(now.slice(5,7));
    for(let i=0;i<monthDifference;i++) await tenant.locator('[data-calendar-month="1"]').click();
    await expect(tenant.locator(`[data-calendar-date="${due}"]`)).toHaveClass(/has-bills/);
    await tenant.locator(`[data-calendar-date="${due}"]`).click();
    await expect(tenant.locator(`[data-calendar-date="${due}"] .calendar-category--electricity`)).toBeVisible();
    await expect(tenant.locator(".tenant-calendar__selected")).toContainText(/Meralco/i);
    await tenant.locator('[data-calendar-month="1"]').click();
    await tenant.locator('[data-calendar-today]').click();
    await expect(tenant.locator(`[data-calendar-date="${now}"]`)).toHaveAttribute("aria-pressed", "true");
    await mark.click();
    await expect(tenant.locator(`[data-home-track-utility="${bill.id}"]`)).toHaveText("Undo mark");
    assert.equal(store.get("bills",other.id).utilityTrackingStatus,"not_marked_paid");
    assert.equal(store.all("receipts").length,0);
    assert.deepEqual(store.all("bills").filter(b=>b.lines.every(l=>l.category==="rent")).map(b=>[b.id,b.paymentStatus]),rentBefore);
    const forbidden=await tenant.evaluate(async id=>{const {api}=await import("/src/api/client.js");try{await api.post(`/bills/${id}/utility-tracking`,{status:"self_reported_paid",revision:1});return 200;}catch(e){return e.status;}},other.id);
    assert.equal(forbidden,403);
    await tenant.goto(origin+"/#/tenant/notifications");
    await expect(tenant.locator(".notification-feed")).toContainText(`Electricity · ${now.slice(0,7)}`);
    await tenant.locator(`[data-view-bill="${bill.id}"]`).click();
    await expect(tenant.getByRole("dialog")).toContainText("Self-Reported Paid");
    await expect(tenant.getByRole("dialog")).toContainText("Provider payment not verified");
    await tenant.keyboard.press("Escape");
    await tenant.goto(origin+"/#/tenant/bills");
    await expect(tenant.locator('.tenant-filter-disclosure')).not.toHaveAttribute('open', '');
    await tenant.locator(".tenant-filter-disclosure > summary").click();
    await tenant.locator('[data-history-filter="category"]').selectOption("electricity");
    await tenant.locator('[data-history-filter="status"]').selectOption("self_reported_paid");
    await expect(tenant.locator(`[data-track-utility="${bill.id}"]`)).toBeVisible();
    await expect(tenant.locator('[data-history-filter="status"]')).toBeFocused();
    await tenant.reload();
    await expect(tenant.locator('[data-history-filter="category"]')).toHaveValue("electricity");
    await expect(tenant.locator('[data-history-filter="status"]')).toHaveValue("self_reported_paid");
    await expect(tenant.locator(`[data-track-utility="${bill.id}"]`)).toBeVisible();
    await tenant.locator('[data-history-filter="status"]').selectOption("not_marked_paid");
    await expect(tenant.getByText("No bills match your filters",{exact:true})).toBeVisible();
    await tenant.locator('[data-history-filter="status"]').selectOption("");
    await expect(tenant.locator(`[data-track-utility="${bill.id}"]`)).toHaveText("Undo mark");
    await tenant.locator(`[data-track-utility="${bill.id}"]`).click();
    await expect(tenant.locator(`[data-track-utility="${bill.id}"]`)).toHaveText("Mark personally paid");
    const count=store.all("bills").length;
    const [duplicate]=await app.integrations.ingestEmail(utilityEmail(utilityPdf(text.replace("UNMAPPED-TEST","MER-552194"))));
    assert.equal(duplicate.document.processingOutcome,"exception");
    assert.equal(store.all("bills").length,count);
    store.save("mappings",{id:"ocr-fixture-map",unitId:"unt-b",provider:"meralco",account:"MER-12345",category:"electricity"});
    const image=await app.integrations.ingest(readFileSync(new URL("./fixtures/utility.png",import.meta.url)),"clear-synthetic-image.png","image/png");
    assert.equal(image.document.ocrStatus,"validated",JSON.stringify(image.failures));
    assert.equal(image.document.accountRef,"MER-12345");
    assert.equal(image.document.amountDue,100);
    assert.equal(image.billIds.length,3);
    const managerUser=service.login({email:"manager@propertypro.ph",password}).user;
    const adminUser=service.login({email:"admin@propertypro.ph",password}).user;
    const individualUnit=service.writeEntity(managerUser,"units",{propertyId:"prp-b",code:"B-IND",floor:"Ground",floorNumber:0,type:"Studio",monthlyRent:100,arrangement:"individual"});
    const individualTenant=service.writeEntity(managerUser,"tenants",{fullName:"Individual Water Tenant",email:"individual@example.test",unitId:individualUnit.id,leaseStart:start,assignmentStart:start});
    service.userWrite(adminUser,{name:individualTenant.fullName,email:individualTenant.email,role:"tenant",tenantId:individualTenant.id,password});
    service.writeEntity(managerUser,"mappings",{unitId:individualUnit.id,provider:"Manila Water",account:"MW-IND-001",category:"water"});
    const waterText=`SYNTHETIC WATER TEST\nManila Water\nAccount: MW-IND-001\nAmount Due: 220.00\nDue Date: ${due}\nBilling Period: ${start} to ${now}`;
    const water=await app.integrations.ingest(utilityPdf(waterText),"individual-water.pdf","application/pdf");
    assert.equal(water.document.ocrStatus,"validated",JSON.stringify(water.failures));
    assert.equal(water.billIds.length,1);
    const waterBill=store.get("bills",water.billIds[0]);
    assert.equal(waterBill.totalDue,220);
    assert.equal(waterBill.tenantId,individualTenant.id);
    const waterPage=await browser.newPage({viewport:{width:390,height:844}});
    waterPage.on("pageerror",e=>errors.push(e.message));
    await login(waterPage,"individual@example.test");
    await expect(waterPage.locator(".tenant-utility-card")).toContainText("Water");
    await expect(waterPage.locator(".tenant-utility-card")).toContainText("220.00");
    await waterPage.locator(`[data-home-track-utility="${waterBill.id}"]`).click();
    await expect(waterPage.locator(`[data-home-track-utility="${waterBill.id}"]`)).toHaveText("Undo mark");
    assert.equal(store.get("bills",waterBill.id).utilityTrackingStatus,"self_reported_paid");
    assert.equal(store.all("receipts").length,0);
    assert.deepEqual(errors,[]);
  } finally {
    await browser?.close(); await app.close();
    if(dirname(resolve(dir))!==resolve(tmpdir())) throw new Error("Unsafe test cleanup path");
    rmSync(dir,{recursive:true,force:true});
  }
});
