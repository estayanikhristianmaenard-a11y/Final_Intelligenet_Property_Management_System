import test from "node:test";
import assert from "node:assert/strict";
import { chromium, expect } from "@playwright/test";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, resolve, join } from "node:path";
import { Store, DEFAULT_WORKSPACE } from "../server/store.js";
import { Service } from "../server/service.js";
import { bootstrap } from "../server/bootstrap.js";
import { Integrations } from "../server/integrations.js";
import { createApp } from "../server/index.js";
import { utilityText } from "./fixtures.js";

test("browser: clean login, Staff proposal, Manager decision, Tenant isolation and Admin filters", { timeout: 120000 }, async () => {
  const dir = mkdtempSync(join(tmpdir(), "rentara-staff-browser-"));
  const store = new Store(join(dir, "test.sqlite")), service = new Service(store);
  const password = "StaffBrowser!2026";
  bootstrap(service, { demo: true, demoStart: "2026-01-01", adminPassword: password, managerPassword: password, tenantPassword: password });
  service.userWrite(store.get("users", "usr-admin"), { name: "Test Operations", email: "operations@example.test", role: "staff", workspaceId: DEFAULT_WORKSPACE, password });
  store.save("mappings", { ...store.get("mappings", "map-demo"), account: "MER-12345" });
  const integrations = new Integrations(service, dir, {});
  const text = utilityText.replace("Due Date: 2026-03-05", "Due Date: unreadable");
  const source = await integrations.ingest(Buffer.from(text), "needs-review.txt", "text/plain", {}, async () => ({ text, confidence: 100 }));
  const app = createApp({ store, integrations, dataDir: dir, env: { ALLOWED_ORIGINS: "http://127.0.0.1:8127" } });
  let browser;
  try {
    await new Promise(r => app.server.listen(8127, "127.0.0.1", r));
    browser = await chromium.launch({ headless: true, ...(process.platform === "win32" ? { executablePath: process.env.BROWSER_EXECUTABLE || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe" } : {}) });
    const errors = [];
    async function login(email, mobile = false) {
      const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 } });
      const page = await context.newPage(); page.on("pageerror", e => errors.push(e.message));
      await page.goto("http://127.0.0.1:8127/");
      await expect(page.locator(".auth-demo-shortcuts")).toHaveCount(0);
      await page.locator("#login-email").fill(email); await page.locator("#login-password").fill(password);
      await page.getByRole("button", { name: /Sign in/ }).click();
      // A click resolves before asynchronous authentication and home rendering.
      // Do not navigate away from the login request while it is still pending.
      await expect(page.locator(".app-shell")).toBeVisible();
      await expect(page.locator("main h1")).toHaveCount(1);
      await expect(page.locator(".skeleton, .skeleton-line")).toHaveCount(0);
      return page;
    }
    const staff = await login("operations@example.test", true);
    await expect(staff.locator("h1")).toHaveText("Daily operations");
    await staff.getByRole("link", { name: /Needs action/ }).click();
    await expect(staff.locator("[data-responsibility-filter]")).toHaveValue("staff");
    await expect(staff.locator("[data-case-select]:visible")).not.toHaveCount(0);
    await staff.locator("[data-responsibility-filter]").selectOption("returned");
    await expect(staff.locator("[data-case-select]:visible")).toHaveCount(0);
    await expect(staff.locator("[data-queue-count]")).toHaveText("0 cases in this queue");
    await staff.goto("http://127.0.0.1:8127/#/bills?tab=incoming");
    await expect(staff.locator("[data-automation-status]")).toContainText("Mailbox not configured");
    await expect(staff.locator('[data-intake-result="review"]')).toHaveCount(1);
    await staff.locator("[data-intake-filter]").selectOption("processed");
    await expect(staff.locator("[data-intake-result]:visible")).toHaveCount(0);
    await expect(staff.locator("[data-intake-empty]")).toBeVisible();
    await staff.locator("[data-intake-filter]").selectOption("all");
    await expect(staff.locator("[data-intake-result]:visible")).toHaveCount(1);
    await staff.locator("[data-automation-status] > summary").click();
    await expect(staff.locator("[data-automation-status]")).toContainText("Not recorded yet");
    await staff.goto("http://127.0.0.1:8127/#/bills?tab=exceptions");
    await expect(staff.getByRole("button", { name: "Prepare correction" }).first()).toBeVisible();
    await staff.route("**/api/v1/incoming/*/source", route=>route.fulfill({status:503,body:"Temporary preview failure"}));
    await staff.getByRole("button", { name: "Prepare correction" }).first().click();
    await expect(staff.getByRole("region", { name:"Original utility bill" })).toBeVisible();
    await expect(staff.getByRole("button",{name:"Retry original",exact:true})).toBeVisible();
    await staff.locator('.case-edit input[name="dueDate"]').fill("2026-03-05");
    await staff.unroute("**/api/v1/incoming/*/source");
    await staff.getByRole("button",{name:"Retry original",exact:true}).click();
    await expect(staff.locator('.case-edit input[name="dueDate"]')).toHaveValue("2026-03-05");
    await expect(staff.getByRole("link", { name:"Download original", exact:true })).toBeVisible();
    await staff.locator('.case-edit input[name="dueDate"]').fill("2026-03-05");
    await staff.getByRole("button", { name: "Submit for Manager review" }).click();
    await expect(staff.locator('.case-edit textarea[name="reason"]')).toHaveAttribute("aria-invalid","true");
    await expect(staff.locator('.case-edit input[name="dueDate"]')).toHaveValue("2026-03-05");
    await staff.locator('.case-edit textarea[name="reason"]').fill("Verified date in the source document");
    await staff.route("**/api/v1/incoming/*/proposals",route=>route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({message:"Temporary test failure"})}));
    await staff.getByRole("button", { name: "Submit for Manager review" }).click();
    await expect(staff.locator("[data-case-error]")).toContainText("Temporary test failure");
    await expect(staff.locator('.case-edit input[name="dueDate"]')).toHaveValue("2026-03-05");
    await expect(staff.locator('.case-edit textarea[name="reason"]')).toHaveValue("Verified date in the source document");
    assert.equal(store.all("correction_proposals").length,0);
    await staff.unroute("**/api/v1/incoming/*/proposals");
    await staff.getByRole("button", { name: "Submit for Manager review" }).click();
    await expect(staff.locator(".proposal-record")).toContainText("With Manager");
    await expect(staff.locator("[data-case-prepare],[data-case-save]")).toHaveCount(0);
    await staff.locator("[data-responsibility-filter]").selectOption("staff");
    await expect(staff.locator("[data-case-select]:visible")).toHaveCount(0);
    await staff.locator("[data-responsibility-filter]").selectOption("manager");
    await expect(staff.locator(".proposal-record")).toContainText("With Manager");
    await expect(staff.locator("[data-case-select]:visible")).not.toHaveCount(0);
    assert.equal(store.get("incoming", source.document.id).ocrStatus, "failed");
    await staff.goto("http://127.0.0.1:8127/#/units");
    await expect(staff.getByRole("button", { name: "Add unit", exact: true })).toBeHidden();
    await staff.locator('[data-edit-entity="units"]').first().click();
    await expect(staff.locator('.modal input[name="monthlyRent"]')).toHaveCount(0);
    await staff.getByRole("button", { name: "Cancel", exact: true }).click();
    const manager = await login("manager@propertypro.ph");
    await expect(manager.locator("h1")).toHaveText("Dashboard");
    await expect(manager.locator(".manager-review-queue")).toContainText("Your decisions");
    await expect(manager.getByRole("link", { name: /Staff proposals/ })).toContainText("1");
    await manager.goto("http://127.0.0.1:8127/#/bills?tab=exceptions");
    await manager.getByRole("button", { name: "Reject proposal" }).click();
    await manager.locator('.modal textarea[name="reason"]').fill("Please include the verified source date in your findings.");
    await manager.getByRole("button", { name: "Save", exact: true }).click();
    await expect(manager.locator(".modal")).toHaveCount(0);
    assert.equal(store.get("incoming", source.document.id).ocrStatus, "failed");
    await staff.goto("http://127.0.0.1:8127/#/bills?tab=exceptions&queue=returned");
    await expect(staff.locator(".proposal-record")).toContainText("Please include the verified source date");
    await expect(staff.locator("[data-case-select]:visible")).not.toHaveCount(0);
    await staff.getByRole("button", { name: "Prepare correction" }).first().click();
    await staff.locator('.case-edit input[name="dueDate"]').fill("2026-03-05");
    await staff.locator('.case-edit textarea[name="reason"]').fill("Source clearly states Due Date 2026-03-05.");
    await staff.getByRole("button", { name: "Submit for Manager review" }).click();
    await expect(staff.locator(".proposal-record")).toHaveCount(0);
    await expect(staff.locator("[data-case-select]:visible")).toHaveCount(0);
    await manager.goto("http://127.0.0.1:8127/#/bills?tab=exceptions&queue=manager");
    manager.once("dialog", dialog => dialog.accept());
    await manager.getByRole("button", { name: "Authorize correction" }).click();
    await expect(manager.locator(".proposal-record")).toHaveCount(0);
    await manager.locator("[data-responsibility-filter]").selectOption("all");
    await expect(manager.locator(".proposal-record").first()).toContainText("Applied");
    assert.equal(store.get("incoming", source.document.id).ocrStatus, "validated");
    await manager.goto("http://127.0.0.1:8127/#/bills?tab=incoming");
    await expect(manager.locator('[data-intake-result="processed"]')).toHaveCount(1);
    await expect(manager.locator('[data-intake-result="processed"]')).toContainText("Processed");
    await expect(manager.locator('[data-intake-result="processed"] .ocr-bill__side')).toContainText("Unit");
    const tenant = await login("maria.santos@gmail.com", true);
    await expect(tenant.locator("h1")).toContainText("My home", { ignoreCase: true });
    const tenantUser = store.all("users").find(u => u.email === "maria.santos@gmail.com");
    assert.ok(service.bills(tenantUser).some(b => b.sourceId === source.document.id));
    await tenant.goto("http://127.0.0.1:8127/#/bills?tab=exceptions");
    await expect(tenant.locator("h1")).toContainText("not available");
    const admin = await login("admin@propertypro.ph");
    await admin.goto("http://127.0.0.1:8127/#/admin/settings");
    await admin.locator("[data-account-role]").selectOption("staff");
    await expect(admin.locator('[aria-label="User accounts"] tbody tr:visible')).toHaveCount(1);
    await expect(admin.locator('[aria-label="User accounts"] tbody tr:visible')).toContainText("Test Operations");
    await admin.locator("[data-workspace-members]").first().click();
    assert.deepEqual(errors, []);
    assert.equal(await staff.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  } finally {
    await browser?.close(); await app.close();
    assert.equal(dirname(resolve(dir)), resolve(tmpdir())); rmSync(dir, { recursive: true, force: true });
  }
});
